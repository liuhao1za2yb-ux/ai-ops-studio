// ---------- CSV 数据清洗：合成测试数据生成器 ----------
// 生成一份贴近企业订单表格的合成数据，含重复、缺失、格式不一致
// 字段：订单号 / 下单时间 / 客户姓名 / 手机号 / 商品名称 / SKU / 数量 / 单价 / 实付金额 / 收货地址 / 订单状态
export function generateCsvDatasets() {
  const surnames = ['王', '李', '张', '刘', '陈', '杨', '赵', '黄', '周', '吴', '徐', '孙', '马', '朱', '胡', '郭']
  const givenNames = ['晓明', '雅芳', '国伟', '海洋', '静怡', '磊', '丽华', '志杰', '敏', '强', '雪', '军', '婷', '波', '娜', '涛']
  const regions = ['北京市朝阳区', '上海市浦东新区', '广州市天河区', '深圳市南山区', '杭州市西湖区', '成都市武侯区', '武汉市洪山区', '西安市雁塔区']

  const rnd = (n) => Math.floor(Math.random() * n)
  const makeName = (i) => surnames[i % surnames.length] + givenNames[(i * 7) % givenNames.length]
  // 生成唯一手机号（合成数据，13x 开头）
  const makePhone = (i) => '13' + String(100000000 + (i * 7919) % 900000000).padStart(9, '0')

  // 商品目录（SKU 对应）
  const products = [
    { sku: 'SKU-1001', name: '氨基酸洗发水 500ml' },
    { sku: 'SKU-1002', name: '修护护发素 400ml' },
    { sku: 'SKU-1003', name: '保湿补水面膜 10片装' },
    { sku: 'SKU-1004', name: '焕亮精华液 30ml' },
  ]
  const statuses = ['已支付', '待发货', '已发货', '已完成', '已取消']

  const pad = (n) => String(n).padStart(2, '0')

  // 数据集 A：订单主表（含手机号格式不一致、日期格式不一致、姓名缺失）
  const rowsA = []
  const baseA = 380
  for (let i = 0; i < baseA; i++) {
    const phoneVal = makePhone(i)
    let phoneOut = phoneVal
    // 制造格式不一致：部分手机号加横线或空格
    if (i % 7 === 0) phoneOut = phoneVal.slice(0, 3) + '-' + phoneVal.slice(3, 7) + '-' + phoneVal.slice(7)
    else if (i % 11 === 0) phoneOut = phoneVal.slice(0, 3) + ' ' + phoneVal.slice(3, 7) + ' ' + phoneVal.slice(7)

    // 日期格式不一致：部分用 / 分隔
    const mm = 1 + rnd(12)
    const dd = 1 + rnd(28)
    const date = i % 3 === 0 ? `2024/${pad(mm)}/${pad(dd)}` : `2024-${pad(mm)}-${pad(dd)}`

    // 姓名缺失
    let name = makeName(i)
    if (i % 13 === 0) name = ''

    // 关键字段（订单号/实付金额）缺失
    const orderNo = i % 29 === 0 ? '' : 'ORD' + String(10000 + i)
    const amount = (50 + rnd(5000) / 10).toFixed(2)
    const payAmount = i % 37 === 0 ? '' : amount

    rowsA.push({ orderNo, orderTime: date, name, phone: phoneOut, productName: products[rnd(products.length)].name, sku: products[rnd(products.length)].sku, qty: 1 + rnd(10), unitPrice: (10 + rnd(500)).toFixed(2), payAmount, address: regions[i % regions.length] + '示例路' + (i + 1) + '号', status: statuses[rnd(statuses.length)] })
  }
  // 注入明确重复行（20 条，直接复制前面已生成的行，订单号相同、商品明细相同）
  for (let i = 0; i < 20; i++) {
    rowsA.push({ ...rowsA[i * 5] })
  }

  // 数据集 B：订单明细（含订单号，用于匹配；含少量重复）
  const rowsB = []
  const baseB = 390
  for (let i = 0; i < baseB; i++) {
    const p = products[rnd(products.length)]
    const orderNo = 'ORD' + String(10000 + i)
    rowsB.push({ orderNo, productName: p.name, sku: p.sku, qty: 1 + rnd(10), unitPrice: (10 + rnd(500)).toFixed(2) })
  }
  // 注入 10 条重复
  for (let i = 0; i < 10; i++) {
    rowsB.push({ ...rowsB[i * 3] })
  }

  // 数据集 C：会员信息（含缺失、日期不一致、重复）
  const rowsC = []
  const baseC = 180
  for (let i = 0; i < baseC; i++) {
    const phoneVal = makePhone(5000 + i)
    const mm = 1 + rnd(12)
    const dd = 1 + rnd(28)
    const joinDate = i % 2 === 0 ? `2023/${pad(mm)}/${pad(dd)}` : `2023-${pad(mm)}-${pad(dd)}`
    let level = ['普通', '银卡', '金卡'][rnd(3)]
    if (i % 17 === 0) level = ''
    rowsC.push({ name: makeName(i + 100), phone: phoneVal, region: regions[i % regions.length], joinDate, level })
  }
  // 注入 20 条重复
  for (let i = 0; i < 20; i++) {
    rowsC.push({ ...rowsC[i * 4] })
  }

  return { customers: rowsA, orders: rowsB, members: rowsC }
}
