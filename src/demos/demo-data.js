function buildLeadComments() {
  return leadCommentTemplates.map((t, i) => {
    const [platform, industry, content, likes, intent, reason, reply] = t
    // 根据 reason 中的意向强度描述分层打分，保证评分可解释、强弱有序
    let level = 70 // 中等意向默认分
    if (/强意向|高价值|明确/.test(reason)) level = 88
    else if (/中强|中等意向|评估期/.test(reason)) level = 76
    else if (/弱意向|无明显|路过|仅/.test(reason)) level = 60
    else if (/延迟/.test(reason)) level = 55
    // 叠加点赞数做小幅修正（点赞越多曝光越大，价值略高）
    const likeBonus = Math.min(5, Math.round(likes / 40))
    const score = Math.min(95, level + likeBonus + ((i * 3) % 4))
    return {
      platform,
      industry,
      content,
      likes,
      intent,
      score,
      reason,
      reply,
      // 用于前端展示的「用户昵称」均为虚构
      nickname: `演示用户${String(i + 1).padStart(2, '0')}`,
    }
  })
}

